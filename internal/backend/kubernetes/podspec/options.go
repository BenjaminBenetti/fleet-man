package podspec

// Outcome is what the table does with a docker run option.
type Outcome string

const (
	// Map translates the option onto the pod (a warning names any part the
	// cluster cannot do exactly as docker does).
	Map Outcome = "map"
	// Delta accepts a difference from docker, with a visible warning.
	Delta Outcome = "delta"
	// Ignore leaves out an option that changes nothing on either side: CLI
	// plumbing, or an option docker itself ignores on Linux.
	Ignore Outcome = "ignore"
	// Refuse fails the create with the option's error code and the reason.
	Refuse Outcome = "refuse"
)

// Option is one row of the table: a docker run option (its canonical name,
// as kubeshim parses it), its outcome in the common case and why. A Map row
// may still refuse a value it cannot carry (--network host without
// privileged pods allowed, --network <custom>); the run's OptionOutcome says
// what happened to the values it gave.
type Option struct {
	Name    string  `json:"name"`
	Outcome Outcome `json:"outcome"`
	Reason  string  `json:"reason"`
	// apply translates the option's values (every one given, in order) and
	// returns the outcome for them, "" for the row's. A row without one is
	// handled by its outcome alone: a Delta warns with the reason, a Refuse
	// refuses with it, and Map and Ignore rows need nothing (Translate reads
	// env, labels, user, workdir and entrypoint from the merged container).
	apply func(t *translation, vals []string) Outcome
}

// Options returns the table, sorted by option name: every docker run and
// docker create option kubeshim parses (kubeshim.RunFlagNames), each exactly
// once.
func Options() []Option {
	return append([]Option(nil), options...)
}

